"""W20, Part A: the map of what each test file reads outside its own area, and the checker that keeps it true.

Standard library only. The map is tools/ci_map.json. `python -m tools.ci_map check` fails (exit 2) when a test file
reads a path the map does not list for it, when a test file has no entry, or when an entry is for a file that is gone.
`python -m tools.ci_map table` prints the markdown table that docs/testing.md holds between two markers.

Exit codes: 0 done, 2 the map is stale or broken, 64 usage.

What the scanner sees: a path built from the repository root in the test code (`REPO / "ui" / "src"`, an f-string
or os.path.join on a name that comes from `__file__`), an import of the `adapters` package, a walk of the whole
repository (`REPO.rglob`, `git ls-files`), and the same through the helper modules a test imports. For the Node
tests: a relative import that leaves the package, a path named in a string, and the literals of a join(). What it
cannot see: a path a child process reads from its own working directory, and a path built from data.
"""
import ast
import json
import posixpath
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MAP_PATH = Path(__file__).resolve().parent / "ci_map.json"
TABLE_BEGIN = "<!-- ci-map:begin (generated by `python -m tools.ci_map table`; tests/test_ci_map.py keeps it true) -->"
TABLE_END = "<!-- ci-map:end -->"

# The first segment of a repository path that counts as "outside the test's own area". umwayi/ and tests/ are the
# python tests' own area and are left out.
ROOT_TOKENS = frozenset({
    "ui", "site", "docs", "adapters", ".kiro", "README.md", "PROJECT.md", "LICENSE", ".gitignore", "pyproject.toml",
    "docs-parts", "rules.yaml", "agents.example.yaml", "autonomy.example.yaml", "schedule.example.yaml", "serve.rules.example.yaml",
    "jobs.yaml", "umwayi.json", "memory", "articles", "workflows", ".github", "tools",
})
PYTHON_TOKENS = ROOT_TOKENS | {"ui/dist", "*"}
NODE_PACKAGES = ("ui", "site")
VALUES = ("all", "map", "none")
# Routes the design requires, whatever else the map says: a change here must run the whole Python suite.
FLOOR = {"umwayi/": False, "tests/": False, "adapters/": False, ".github/": True, "tools/": True}
STAR_METHODS = frozenset({"rglob", "glob", "iterdir"})


class MapError(Exception):
    pass


def reads_match(token, path):
    """True if a test that reads `token` is affected by a change to `path`."""
    if token == "*":
        return True
    return path == token or path.startswith(token + "/")


def _is_str_list(value):
    return isinstance(value, list) and all(isinstance(x, str) and x for x in value)


def validate_map(data):
    if not isinstance(data, dict) or data.get("version") != 1:
        raise MapError("the map must be an object with version 1")
    for key in ("routes", "default", "python", "node"):
        if key not in data:
            raise MapError(f"the map has no '{key}'")
    routes = data["routes"]
    if not isinstance(routes, list) or not routes:
        raise MapError("'routes' must be a list")
    seen = set()
    for r in routes:
        if not isinstance(r, dict) or not isinstance(r.get("match"), str) or not r["match"]:
            raise MapError(f"a route needs a 'match': {r!r}")
        if r["match"] in seen:
            raise MapError(f"route {r['match']} is listed twice")
        seen.add(r["match"])
        _check_route(r, r["match"])
    _check_route(data["default"], "default")
    d = data["default"]
    if not (d.get("full") is True and d.get("python") == "all" and d.get("node") is True):
        raise MapError("the default route must run everything (full, python all, node true)")
    by = {r["match"]: r for r in routes}
    for prefix, full in FLOOR.items():
        r = by.get(prefix)
        if r is None:
            raise MapError(f"route {prefix} is required")
        if r["python"] != "all":
            raise MapError(f"route {prefix} must run all python tests")
        if full and not (r.get("full") is True and r["node"] is True):
            raise MapError(f"route {prefix} must run everything")
    for section, allowed in (("python", PYTHON_TOKENS), ("node", None)):
        entries = data[section]
        if not isinstance(entries, dict):
            raise MapError(f"'{section}' must be an object")
        for name, tokens in entries.items():
            if not isinstance(name, str) or not _is_str_list(tokens):
                raise MapError(f"{section} entry {name!r} must be a list of paths")
            for t in tokens:
                bad = (allowed is not None and t not in allowed) or t.startswith("/") or ".." in t.split("/") or "\\" in t
                if bad:
                    raise MapError(f"{section} entry {name} lists '{t}', which is not a known path")


def _check_route(r, name):
    if r.get("python") not in VALUES:
        raise MapError(f"route {name}: 'python' must be one of {VALUES}")
    if r.get("node") not in (True, False, "map"):
        raise MapError(f"route {name}: 'node' must be true, false or \"map\"")
    if "full" in r and not isinstance(r["full"], bool):
        raise MapError(f"route {name}: 'full' must be true or false")


def load_map(path=MAP_PATH):
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise MapError(f"cannot read the map {path}: {e}")
    validate_map(data)
    return data


# ---------------------------------------------------------------- the python scanner

def _spine(node):
    """For a/b/c return (a, [b, c]) following the left side of `/`."""
    parts = []
    while isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div):
        parts.append(node.right)
        node = node.left
    return node, list(reversed(parts))


def _segments(text):
    return [s for s in re.split(r"[/\\]", text) if s]


def _tokens_of(segments):
    out = set()
    if segments and segments[0] in ROOT_TOKENS:
        out.add(segments[0])
        if segments[:2] == ["ui", "dist"]:
            out.add("ui/dist")
    return out


def _consts(nodes):
    segs = []
    for n in nodes:
        if isinstance(n, ast.Constant) and isinstance(n.value, str):
            segs.extend(_segments(n.value))
        else:
            break
    return segs


def _names(node):
    return {n.id for n in ast.walk(node) if isinstance(n, ast.Name)}


def _where(expr, env, here):
    """The folder (a tuple of parts below the repository root) a path expression stands for, or None if it is not one.
    `here` is the parts of the module file itself, `env` maps a name to its folder."""
    if isinstance(expr, ast.Name):
        return here if expr.id == "__file__" else env.get(expr.id)
    if isinstance(expr, ast.Call):
        f = expr.func
        name = f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", "")
        if name in ("resolve", "absolute", "expanduser") and isinstance(f, ast.Attribute):
            return _where(f.value, env, here)
        if name in ("Path", "abspath", "realpath", "fspath", "str") and len(expr.args) == 1:
            return _where(expr.args[0], env, here)
        if name == "dirname" and len(expr.args) == 1:
            w = _where(expr.args[0], env, here)
            return w[:-1] if w else None
        return None
    if isinstance(expr, ast.Attribute) and expr.attr == "parent":
        w = _where(expr.value, env, here)
        return w[:-1] if w else None
    if (isinstance(expr, ast.Subscript) and isinstance(expr.value, ast.Attribute) and expr.value.attr == "parents"
            and isinstance(expr.slice, ast.Constant) and isinstance(expr.slice.value, int)):
        w = _where(expr.value.value, env, here)
        k = expr.slice.value + 1
        return w[:-k] if w is not None and 0 <= k <= len(w) else None
    if isinstance(expr, ast.BinOp) and isinstance(expr.op, ast.Div):
        w = _where(expr.left, env, here)
        if w is not None and isinstance(expr.right, ast.Constant) and isinstance(expr.right.value, str):
            return w + tuple(_segments(expr.right.value))
    return None


def _module_file(root, dotted):
    base = root.joinpath(*dotted.split("."))
    for cand in (base.with_suffix(".py"), base / "__init__.py"):
        if cand.is_file():
            return cand
    return None


def _file_imports(tree, path, root):
    """The files under tests/ this module imports: [(file, [names imported from it])]."""
    out = []
    pkg_parts = list(path.relative_to(root).parent.parts)
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            for a in n.names:
                if a.name.split(".")[0] == "tests":
                    f = _module_file(root, a.name)
                    if f:
                        out.append((f, []))
        elif isinstance(n, ast.ImportFrom):
            if n.level:
                base = pkg_parts[: len(pkg_parts) - (n.level - 1)]
                mod = ".".join(base + ([n.module] if n.module else []))
            else:
                mod = n.module or ""
            if mod.split(".")[0] != "tests":
                continue
            f = _module_file(root, mod)
            if f:
                out.append((f, [a.name for a in n.names]))
            for a in n.names:
                sub = _module_file(root, mod + "." + a.name)
                if sub:
                    out.append((sub, []))
    return out


def _direct(tree, env, here):
    """Tokens one module reads by itself, given the names that stand for folders (env) and the module's own parts."""
    tokens = set()

    def where(node):
        w = _where(node, env, here)
        return w if w is not None else None

    def below(node, parts):
        w = where(node)
        return _tokens_of(list(w) + parts) if w is not None else set()

    for n in ast.walk(tree):
        if isinstance(n, (ast.Import, ast.ImportFrom)):
            mods = [a.name for a in n.names] if isinstance(n, ast.Import) else [n.module or ""]
            if getattr(n, "level", 0) == 0 and any(m.split(".")[0] == "adapters" for m in mods):
                tokens.add("adapters")
        elif isinstance(n, ast.BinOp) and isinstance(n.op, ast.Div):
            base, rest = _spine(n)
            tokens |= below(base, _consts(rest))
        elif isinstance(n, ast.BinOp) and isinstance(n.op, ast.Add):
            if isinstance(n.right, ast.Constant) and isinstance(n.right.value, str):
                tokens |= below(n.left, _segments(n.right.value))
        elif isinstance(n, ast.JoinedStr):
            prev = None
            for v in n.values:
                if isinstance(v, ast.FormattedValue):
                    prev = v.value
                elif prev is not None and isinstance(v, ast.Constant) and isinstance(v.value, str):
                    tokens |= below(prev, _segments(v.value))
                    prev = None
                else:
                    prev = None
        elif isinstance(n, ast.Call):
            f = n.func
            name = f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", "")
            if name in ("join", "Path") and len(n.args) > 1:
                tokens |= below(n.args[0], _consts(n.args[1:]))
            elif name == "joinpath" and isinstance(f, ast.Attribute):
                tokens |= below(f.value, _consts(n.args))
            if isinstance(f, ast.Attribute) and f.attr in STAR_METHODS and where(f.value) == ():
                tokens.add("*")
            if isinstance(f, ast.Attribute) and f.attr in ("walk", "copytree") and n.args and where(n.args[0]) == ():
                tokens.add("*")
        elif isinstance(n, ast.Constant) and n.value == "ls-files":
            tokens.add("*")
    return tokens


def _own_env(tree, here, imported):
    """Names assigned a path expression, as folders. `imported` seeds the names taken from other test modules."""
    env = dict(imported)
    changed = True
    while changed:
        changed = False
        for n in ast.walk(tree):
            if isinstance(n, ast.Assign) and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name):
                w = _where(n.value, env, here)
                if w is not None and env.get(n.targets[0].id) != w:
                    env[n.targets[0].id] = w
                    changed = True
    return env


def _params(fd):
    a = fd.args
    return [x.arg for x in a.posonlyargs + a.args + a.kwonlyargs if x.arg not in ("self", "cls")]


def _functions(tree):
    return [fd for fd in ast.walk(tree) if isinstance(fd, (ast.FunctionDef, ast.AsyncFunctionDef))]


def _scope_env(fd, base, leaks, here):
    """The folders known inside one function: the module's, the parameters that receive the root, its own locals."""
    seed = {**base, **{n: () for n in leaks.get(fd.name, ()) if n in _params(fd)}}
    return _own_env(fd, here, seed)


def _leaks(trees, envs, here):
    """{function name: parameter names that receive the repository root somewhere}. Inside such a function the
    parameter is the root, so `root / "README.md"` there is a read of README.md. Found by repeating until nothing new."""
    defs = {}
    for tree in trees.values():
        for fd in _functions(tree):
            defs.setdefault(fd.name, []).append(_params(fd))
    leaks = {}
    changed = True
    while changed:
        changed = False
        for p, tree in trees.items():
            scopes = [(tree, envs[p])] + [(fd, _scope_env(fd, envs[p], leaks, here[p])) for fd in _functions(tree)
                                          if fd.name in leaks]
            for node, env in scopes:
                for n in ast.walk(node):
                    if not isinstance(n, ast.Call):
                        continue
                    f = n.func
                    name = f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", "")
                    for params in defs.get(name, ()):
                        hits = [params[i] for i, a in enumerate(n.args) if i < len(params) and _where(a, env, here[p]) == ()]
                        hits += [k.arg for k in n.keywords if k.arg in params and _where(k.value, env, here[p]) == ()]
                        for h in hits:
                            if h not in leaks.setdefault(name, set()):
                                leaks[name].add(h)
                                changed = True
    return leaks


def scan_python(root=REPO):
    """{test file: set of tokens it reads outside its own area}, helper modules included."""
    root = Path(root)
    trees, imports, envs, here = {}, {}, {}, {}
    for p in sorted((root / "tests").rglob("*.py")):
        try:
            trees[p] = ast.parse(p.read_text(encoding="utf-8"), filename=str(p))
        except (SyntaxError, ValueError, OSError) as e:
            raise MapError(f"cannot parse {p.relative_to(root).as_posix()}: {e}")
        imports[p] = _file_imports(trees[p], p, root)
        here[p] = p.relative_to(root).parts
        envs[p] = {}
    for _ in range(6):  # folders flow from a module to the modules that import the name
        changed = False
        for p, tree in trees.items():
            seed = {}
            for f, names in imports[p]:
                for nm in names:
                    if nm in envs.get(f, {}):
                        seed[nm] = envs[f][nm]
            env = _own_env(tree, here[p], seed)
            if env != envs[p]:
                envs[p] = env
                changed = True
        if not changed:
            break
    leaks = _leaks(trees, envs, here)
    direct = {}
    for p, tree in trees.items():
        found = _direct(tree, envs[p], here[p])
        for fd in _functions(tree):
            if fd.name in leaks:
                found |= _direct(fd, _scope_env(fd, envs[p], leaks, here[p]), here[p])
        direct[p] = found
    out = {}
    for p in trees:
        if not (p.name.startswith("test") and p.suffix == ".py"):
            continue
        seen, stack, tokens = set(), [p], set()
        while stack:
            q = stack.pop()
            if q in seen:
                continue
            seen.add(q)
            tokens |= direct.get(q, set())
            stack.extend(f for f, _ in imports.get(q, []))
        out[p.relative_to(root).as_posix()] = tokens
    return out


# ---------------------------------------------------------------- the node scanner

NODE_PATH = re.compile(r"(?<![\w./@-])((?:tests|docs|adapters|umwayi|tools|ui|site|\.kiro|\.github)/[\w./@-]*[\w@-])")
NODE_FROM = re.compile(r"""(?:from|import)\s*\(?\s*['"](\.{1,2}/[^'"]*)['"]""")
NODE_JOIN = re.compile(r"\b(?:join|resolve)\(([^()]*)\)")
NODE_LIT = re.compile(r"""['"]([^'"]*)['"]""")


def _strip_js_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("//"))


def scan_node(root=REPO):
    """{node test file: set of repository paths it reads outside its own package}."""
    root = Path(root)
    out = {}
    for pkg in NODE_PACKAGES:
        for p in sorted((root / pkg / "test").glob("*.test.mjs")):
            rel = p.relative_to(root).as_posix()
            text = _strip_js_comments(p.read_text(encoding="utf-8"))
            found = set()
            for spec in NODE_FROM.findall(text):
                found.add(posixpath.normpath(posixpath.join(posixpath.dirname(rel), spec)))
            for m in NODE_PATH.findall(text):
                found.add(m.rstrip("/"))
            for args in NODE_JOIN.findall(text):
                lits = [x for x in NODE_LIT.findall(args) if x != ".."]
                for i, lit in enumerate(lits):
                    if lit in ROOT_TOKENS | {"tests", "umwayi"}:
                        found.add("/".join(x.strip("/") for x in lits[i:]))
                        break
            out[rel] = {f for f in found if f.split("/")[0] != pkg and not f.startswith("../") and not f.startswith("/")}
    return out


# ---------------------------------------------------------------- the checker

def stale(data, root=REPO, scans=None):
    """Every way the map no longer matches the tests. Empty means it is true. `scans` is a (python, node) pair of
    earlier scan results, so a caller that checks many maps against one tree scans it once."""
    root = Path(root)
    problems = []
    py, node = scans if scans is not None else (scan_python(root), scan_node(root))
    for section, scanned in (("python", py), ("node", node)):
        entries = data[section]
        for name, reads in sorted(scanned.items()):
            if name not in entries:
                problems.append(f"{name}: no entry in the {section} map (it reads {sorted(reads)})")
                continue
            for r in sorted(reads):
                if not any(reads_match(t, r) for t in entries[name]):
                    problems.append(f"{name}: reads '{r}' but the map does not list it")
        for name in sorted(set(entries) - set(scanned)):
            problems.append(f"{name}: the map has an entry but the test file is gone")
    return problems


def table_markdown(data):
    lines = [TABLE_BEGIN, "", "Python test files that read a path outside `tests/` and `umwayi/` (every other Python test file reads nothing "
             f"outside its own area: {sum(1 for t in data['python'].values() if not t)} of {len(data['python'])} files):", "",
             "| test file | reads |", "| --- | --- |"]
    for name, toks in sorted(data["python"].items()):
        if toks:
            lines.append(f"| `{name}` | {', '.join('`' + t + '`' for t in sorted(toks))} |")
    lines += ["", "Node test files that read a path outside their own package (the others read nothing outside it):", "",
              "| test file | reads |", "| --- | --- |"]
    for name, toks in sorted(data["node"].items()):
        if toks:
            lines.append(f"| `{name}` | {', '.join('`' + t + '`' for t in sorted(toks))} |")
    lines += ["", "Which changed path runs which jobs (the longest matching prefix wins; a path matching none runs everything):", "",
              "| changed path | python tests | node job |", "| --- | --- | --- |"]
    words = {"all": "all of them", "map": "only the files that read it (tables above)", "none": "none"}
    nodes = {True: "yes", False: "no", "map": "only if a node test reads it"}
    for r in sorted(data["routes"], key=lambda r: r["match"]):
        extra = " (everything, every version)" if r.get("full") else ""
        lines.append(f"| `{r['match']}` | {words[r['python']]}{extra} | {nodes[r['node']]} |")
    d = data["default"]
    lines.append(f"| anything else | {words[d['python']]} (everything, every version) | {nodes[d['node']]} |")
    lines += ["", TABLE_END]
    return "\n".join(lines)


def main(argv):
    if len(argv) != 1 or argv[0] not in ("check", "table", "scan"):
        print("usage: python -m tools.ci_map check | table | scan", file=sys.stderr)
        return 64
    try:
        data = load_map()
        if argv[0] == "table":
            print(table_markdown(data))
            return 0
        if argv[0] == "scan":
            out = {"python": {k: sorted(v) for k, v in scan_python().items()},
                   "node": {k: sorted(v) for k, v in scan_node().items()}}
            print(json.dumps(out, indent=1, sort_keys=True))
            return 0
        problems = stale(data)
    except MapError as e:
        print(f"ci_map: {e}", file=sys.stderr)
        return 2
    except Exception as e:  # fail closed
        print(f"ci_map: unexpected error: {e!r}", file=sys.stderr)
        return 2
    for p in problems:
        print(f"ci_map: {p}", file=sys.stderr)
    if problems:
        print("ci_map: update tools/ci_map.json (python -m tools.ci_map scan shows what each file reads), then paste "
              "`python -m tools.ci_map table` into docs/testing.md", file=sys.stderr)
        return 2
    print("ci_map: the map is true")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
