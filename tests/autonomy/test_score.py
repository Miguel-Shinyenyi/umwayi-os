class WorkedExampleTests(unittest.TestCase):
    """design.md, the worked example: window 90, z 2.58, revert_weight 3."""

    def test_the_three_computed_cases_and_low_data(self):
        for case, (a, e, r, v), want in ((1, (70, 3, 1, 0), 834), (2, (80, 2, 0, 0), 884), (3, (80, 2, 0, 1), 838),
                                         (6, (20, 0, 0, 0), 750)):
            with self.subTest(case=case):
                self.assertEqual(autonomy.wilson(a, e, r, v, 3, 258), want)

    def test_the_steps_of_case_1_to_six_places(self):
        steps = autonomy.wilson_steps(70, 3, 1, 0, 3, 258)
        self.assertEqual((steps["s"], steps["f"], steps["n"]), (70, 4, 74))
        for key, want in (("p", 0.945946), ("centre", 0.990922), ("spread", 0.081377), ("bound", 0.834482)):
            self.assertEqual(round(steps[key], 6), want, key)

    def test_the_thresholds_of_l13_q8(self):
        """38 clean approvals pass a bound of 850 and 37 do not; 60 with two failures pass and 59 do not."""
        self.assertEqual((autonomy.wilson(38, 0, 0, 0, 3, 258), autonomy.wilson(37, 0, 0, 0, 3, 258)), (850, 847))
        self.assertEqual((autonomy.wilson(60, 2, 0, 0, 3, 258), autonomy.wilson(59, 2, 0, 0, 3, 258)), (851, 848))


class FormulaTests(unittest.TestCase):
    def test_two_hundred_fixed_tuples(self):
        self.assertEqual(len(FIXED), 200)
        for a, e, r, v, w, z, want in FIXED:
            with self.subTest(t=(a, e, r, v, w, z)):
                self.assertEqual(autonomy.wilson(a, e, r, v, w, z), want)

    def test_no_record_scores_zero(self):
        self.assertEqual(autonomy.wilson(0, 0, 0, 0, 3, 258), 0)

    def test_only_failures_score_zero_and_the_score_stays_between_0_and_1000(self):
        for t in ((0, 5, 5, 5), (0, 0, 0, 1), (1000000, 0, 0, 0), (1, 0, 0, 0)):
            s = autonomy.wilson(*t, 3, 258)
            self.assertTrue(0 <= s <= 1000, (t, s))
        self.assertEqual(autonomy.wilson(0, 5, 5, 5, 3, 258), 0)

    def test_a_revert_counts_revert_weight_failures_on_top_of_its_approval(self):
        self.assertEqual(autonomy.wilson_steps(80, 2, 0, 1, 3, 258)["f"], 5)
        self.assertEqual(autonomy.wilson(80, 2, 0, 1, 3, 258), autonomy.wilson(80, 5, 0, 0, 3, 258))
        self.assertLess(autonomy.wilson(80, 2, 0, 1, 100, 258), autonomy.wilson(80, 2, 0, 1, 1, 258))

    def test_an_edit_and_a_rejection_are_one_failure_each(self):
        self.assertEqual(autonomy.wilson(80, 1, 1, 0, 3, 258), autonomy.wilson(80, 2, 0, 0, 3, 258))

    def test_the_score_is_rounded_down(self):
        steps = autonomy.wilson_steps(80, 2, 0, 0, 3, 258)
        self.assertEqual(round(steps["bound"], 6), 0.884568)
        self.assertEqual(autonomy.wilson(80, 2, 0, 0, 3, 258), 884)  # 884.568 is never 885
        for t in FIXED:
            b = autonomy.wilson_steps(*t[:6])["bound"] if sum(t[:4]) else 0.0
            self.assertLessEqual(t[6], b * 1000 + 1e-9)

    def test_a_wider_confidence_gives_a_lower_score(self):
        self.assertGreater(autonomy.wilson(80, 2, 0, 0, 3, 196), autonomy.wilson(80, 2, 0, 0, 3, 258))
        self.assertGreater(autonomy.wilson(80, 2, 0, 0, 3, 258), autonomy.wilson(80, 2, 0, 0, 3, 400))


